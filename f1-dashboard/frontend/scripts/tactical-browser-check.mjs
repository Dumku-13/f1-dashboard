// Local integration smoke check. Uses bundled Playwright without adding an app dependency.
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { readFileSync } from 'node:fs'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'C:/Users/jayma/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  const captured = JSON.parse(readFileSync(new URL('../fixtures/openf1-location-zandvoort-2024.json', import.meta.url), 'utf8'))
  await page.route('https://api.openf1.org/v1/**', async route => {
    const url = new URL(route.request().url())
    const endpoint = url.pathname.split('/').at(-1)
    const data = endpoint === 'sessions' ? [{session_key:9582,meeting_key:1243,year:Number(url.searchParams.get('year') || 2024),session_name:'Race',session_type:'Race',country_name:'Netherlands',location:'Zandvoort',date_start:'2024-08-25T14:25:00Z',date_end:'2024-08-25T16:00:00Z'}]
      : endpoint === 'location' ? captured : endpoint === 'drivers' ? [{driver_number:1,full_name:'Max Verstappen',name_acronym:'VER'}] : []
    await route.fulfill({ json: data })
  })
  await page.goto('http://localhost:3000/tactical', { waitUntil: 'domcontentloaded' })
  await page.getByRole('combobox', { name: 'Race / session' }).locator('option[value="9582"]').waitFor({ state: 'attached' })
  await page.getByRole('combobox', { name: 'Season', exact: true }).selectOption('2024')
  await page.getByRole('button', { name: 'Load race', exact: true }).click()
  await page.getByText('Zandvoort · Race · 2024-08-25', { exact: true }).waitFor()
  const notice = page.getByRole('button', { name: 'Understood', exact: true })
  if (await notice.isVisible()) await notice.click()
  await page.getByRole('button', { name: 'Load synthetic demo' }).click()
  await page.getByRole('button', { name: /04Lando Norris/ }).click()
  await page.keyboard.press('1')
  assert.equal(await page.locator('[data-ops-mode]').getAttribute('data-ops-mode'), 'default')
  await page.keyboard.press('2')
  assert.equal(await page.locator('[data-ops-mode]').getAttribute('data-ops-mode'), 'thermal')
  assert.match(await page.locator('.ops-map-surface').evaluate(el => getComputedStyle(el).filter), /url/)
  await page.screenshot({ path: 'tactical-thermal.png', fullPage: true })
  const input = page.getByRole('textbox', { name: 'Tactical command' })
  await input.fill('1')
  await input.press('2')
  assert.equal(await page.locator('[data-ops-mode]').getAttribute('data-ops-mode'), 'thermal')
  await input.fill('Engineer, activate thermal')
  await input.press('Enter')
  assert.equal(await page.locator('[data-ops-mode]').getAttribute('data-ops-mode'), 'thermal')
  await input.fill('Engineer, track Max Verstappen')
  await input.press('Enter')
  assert.equal(await page.getByRole('button', { name: /01Max Verstappen/ }).getAttribute('aria-pressed'), 'true')
  await input.fill('chase cam'); await input.press('Enter')
  assert.equal(await page.getByRole('button', { name: 'Chase', exact: true }).getAttribute('aria-pressed'), 'true')
  await input.fill('display interval gaps'); await input.press('Enter')
  assert.equal(await page.getByRole('checkbox', { name: 'Show recorded interval gaps' }).isChecked(), true)
  await page.getByRole('button', { name: 'Normal view (key 3)' }).click()
  await page.getByRole('button', { name: 'Play replay' }).click()
  const timeline = page.getByRole('slider', { name: 'Replay timeline' })
  const before = Number(await timeline.inputValue())
  await page.waitForTimeout(300)
  assert.ok(Number(await timeline.inputValue()) > before)
  await page.getByRole('button', { name: 'Pause replay' }).click()
  await page.screenshot({ path: 'tactical-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 375, height: 900 })
  await page.screenshot({ path: 'tactical-mobile.png', fullPage: true })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile page overflows')
  await page.getByLabel('Import OpenF1 JSON', { exact: true }).setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{}') })
  await page.getByRole('alert').filter({ hasText: 'location records' }).waitFor()
  await page.getByLabel('Import OpenF1 JSON', { exact: true }).setInputFiles(fileURLToPath(new URL('../fixtures/openf1-location-zandvoort-2024.json', import.meta.url)))
  await page.getByText('IMPORTED / HISTORICAL', { exact: false }).waitFor()
  await page.getByRole('button', { name: /Car 1\b.*Position only/ }).waitFor()
  await page.getByRole('button', { name: 'Live session', exact: true }).click()
  await page.getByRole('region', { name: 'Live race timing' }).waitFor()
  assert.equal(await page.getByRole('button', { name: 'Live session', exact: true }).getAttribute('aria-pressed'), 'true')
  await page.getByRole('button', { name: 'Past races', exact: true }).click()
  assert.deepEqual(errors, [])
  console.log('PASS: HUD modes, typing guard, voice grammar routing, driver lock, chase, intervals, replay clock, invalid import, 375px layout; no client exceptions.')
} finally { await browser.close() }
